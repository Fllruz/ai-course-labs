def main():
    """Выполнение адаптированного запроса."""

    print("=" * 80)
    print("АДАПТИРОВАННЫЙ ЗАПРОС ПО ТЕМЕ ДИПЛОМА")
    print("=" * 80)

    # Инициализация клиента
    iam_token = os.getenv("YANDEX_IAM_TOKEN")
    folder_id = os.getenv("YANDEX_FOLDER_ID")

    client = YandexGPTClient(iam_token, folder_id)

    # Получение персонализированного промпта
    prompt = get_specialty_prompt()

    print("\nЗАПРОС:")
    print("-" * 80)
    print(prompt)
    print("-" * 80)

    # Выполнение запроса
    print("\nОТВЕТ МОДЕЛИ:")
    print("-" * 80)

    response = client.generate(prompt, temperature=0.4)
    print(response["text"])

    print("-" * 80)
    print(f"\nТокены: вход={response['tokens_input']}, выход={response['tokens_output']}")

    # Сохранение результата
    with open("docs/specialty_response.txt", "w", encoding="utf-8") as f:
        f.write("=" * 80 + "\n")
        f.write("ЗАПРОС ДЛЯ НЕЙРОСЕТИ ПО ТЕМЕ ДИПЛОМА\n")
        f.write(f"Тема: Интеллектуальная система управления видеокамерой с функцией слежения за объектами\n")
        f.write(f"Автор: Ходжиев Фируз Фарходович\n")
        f.write("=" * 80 + "\n\n")
        f.write(prompt)
        f.write("\n\n" + "=" * 80 + "\n")
        f.write("ОТВЕТ НЕЙРОСЕТИ\n")
        f.write("=" * 80 + "\n\n")
        f.write(response["text"])
        f.write("\n\n" + "=" * 80 + "\n")
        f.write(f"Статистика: токенов на входе = {response['tokens_input']}, токенов на выходе = {response['tokens_output']}\n")

    print("\n✅ Результат сохранён в docs/specialty_response.txt")


if __name__ == "__main__":
    main()